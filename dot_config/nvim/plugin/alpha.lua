local function stop_timer()
	if not timer then
		return
	end
	if timer and not timer:is_closing() then
		timer:stop()
		timer:close()
	end
	timer = nil
end
local function start_timer()
	stop_timer()
	timer = vim.uv.new_timer()
	if not timer then
		return
	end
	timer:start(
		0,
		400,
		vim.schedule_wrap(function()
			if vim.bo.filetype ~= "alpha" then
				stop_timer()
				return
			end
			step = step % #frames + 1
			art.val = frames[step]
			pcall(alpha.redraw)
		end)
	)
end

vim.api.nvim_create_autocmd("User", {
	pattern = "AlphaReady",
	callback = start_timer,
})
vim.api.nvim_create_autocmd("User", {
	pattern = "AlphaClosed",
	callback = stop_timer,
})
